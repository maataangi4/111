function normalizeName(name: string) {
  return name
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '')
    .trim()
}

function parsePercentValue(s: string): number {
  const txt = s.trim().toLowerCase()
  if (!txt) return 0
  if (txt.includes('<')) {
    const n = Number(txt.replace(/[^0-9.]/g, ''))
    return Number.isFinite(n) ? Math.max(0, n / 2) : 0
  }
  const nums = txt.match(/\d+(\.\d+)?/g)?.map(Number) ?? []
  if (nums.length >= 2) return (nums[0]! + nums[1]!) / 2
  if (nums.length === 1) return nums[0]!
  return 0
}

export function getPotencyByStrainName(name: string): {
  thc: number
  cbd: number
  thcLabel: string
  cbdLabel: string
} | null {
  const key = normalizeName(name)
  let row = STRAIN_POTENCY_ROWS.find((r) => normalizeName(r.name) === key)
  if (!row && key.length >= 5) {
    row = STRAIN_POTENCY_ROWS.find((r) => {
      const rk = normalizeName(r.name)
      return rk.includes(key) || key.includes(rk)
    })
  }
  if (!row) return null
  const thc = parsePercentValue(row.thc)
  const cbd = parsePercentValue(row.cbd)
  return {
    thc: Math.max(0, Math.min(100, thc)),
    cbd: Math.max(0, Math.min(100, cbd)),
    thcLabel: row.thc,
    cbdLabel: row.cbd,
  }
}

