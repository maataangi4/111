const all: Record<AppLocale, MessageDict> = { es, ru }

export function t(
  locale: AppLocale,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const parts = key.split('.')
  let cur: string | MessageDict | undefined = all[locale]
  for (const p of parts) {
    if (!isDict(cur)) return key
    cur = cur[p]
  }
  if (typeof cur !== 'string') return key
  if (!vars) return cur
  let s = cur
  for (const [vk, vv] of Object.entries(vars)) {
    s = s.split(`{${vk}}`).join(String(vv))
  }
  return s
}
